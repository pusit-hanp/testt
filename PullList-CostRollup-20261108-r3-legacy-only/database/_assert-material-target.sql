-- Shared guard, called by deployment scripts. No DDL or application DML here.
-- Input is trusted operator configuration; use only ordinary DB_NAME characters.
SET SERVEROUTPUT ON
SET VERIFY OFF
SET DEFINE ON
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
ACCEPT CR_EXPECTED_DB CHAR PROMPT 'Approved DEV/TEST/UAT DB_NAME (from preflight): '
ACCEPT CR_EXPECTED_SERVICE CHAR PROMPT 'Approved DEV/TEST/UAT SERVICE_NAME (from preflight): '
ACCEPT CR_STAGE CHAR PROMPT 'Deployment environment (DEV, TEST or UAT; PROD forbidden): '
ACCEPT CR_DDL_CONFIRM CHAR PROMPT 'Type APPLY_COSTROLLUP_DDL to allow this script: '

DECLARE
    V_DB VARCHAR2(128) := SYS_CONTEXT('USERENV', 'DB_NAME');
    V_USER VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
    V_SCHEMA VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    IF UPPER(TRIM('&&CR_STAGE')) NOT IN ('DEV', 'TEST', 'UAT')
       OR TRIM('&&CR_STAGE') IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Only approved DEV/TEST/UAT is allowed; PROD requires a separate company change.');
    END IF;
    IF TRIM('&&CR_EXPECTED_DB') IS NULL
       OR UPPER(V_DB) <> UPPER(TRIM('&&CR_EXPECTED_DB')) THEN
        RAISE_APPLICATION_ERROR(-20002, 'DB_NAME does not match the approved target.');
    END IF;
    IF TRIM('&&CR_EXPECTED_SERVICE') IS NULL
       OR UPPER(SYS_CONTEXT('USERENV', 'SERVICE_NAME')) <> UPPER(TRIM('&&CR_EXPECTED_SERVICE')) THEN
        RAISE_APPLICATION_ERROR(-20005, 'SERVICE_NAME does not match the approved target.');
    END IF;
    IF V_USER <> 'MATERIAL' OR V_SCHEMA <> 'MATERIAL' THEN
        RAISE_APPLICATION_ERROR(-20003, 'Connect as MATERIAL; CURRENT_SCHEMA must also be MATERIAL.');
    END IF;
    IF TRIM('&&CR_DDL_CONFIRM') <> 'APPLY_COSTROLLUP_DDL'
       OR TRIM('&&CR_DDL_CONFIRM') IS NULL THEN
        RAISE_APPLICATION_ERROR(-20004, 'DDL was not confirmed.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('Target: ' || V_DB || ' / ' ||
        SYS_CONTEXT('USERENV', 'SERVICE_NAME') || ' / ' || V_SCHEMA);
END;
/
UNDEFINE CR_EXPECTED_DB
UNDEFINE CR_EXPECTED_SERVICE
UNDEFINE CR_STAGE
UNDEFINE CR_DDL_CONFIRM
