DECLARE
    V_COUNT NUMBER;
    V_ROWS NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TABLES WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP';
    IF V_COUNT = 1 THEN
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PULLLIST_COSTROLLUP' INTO V_ROWS;
        DBMS_OUTPUT.PUT_LINE('Existing rows before migration: ' || V_ROWS || '. Preserve export and compare all existing values after migration.');
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PULLLIST_COSTROLLUP WHERE CUST_CODE IS NULL OR LENGTH(CUST_CODE) <> 2 OR TRIM(CUST_CODE) IS NULL OR CUST_CODE <> UPPER(TRIM(CUST_CODE)) OR REGEXP_LIKE(CUST_CODE, ''[[:space:]]'')' INTO V_ROWS;
        DBMS_OUTPUT.PUT_LINE('Invalid/noncanonical customers: ' || V_ROWS || '. Reconcile explicitly; no identifiers will be normalized.');
        SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP' AND COLUMN_NAME IN ('FROM_DATE', 'TO_DATE');
        IF V_COUNT = 2 THEN
            EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM PULLLIST_COSTROLLUP WHERE (FROM_DATE IS NULL AND TO_DATE IS NOT NULL) OR (FROM_DATE IS NOT NULL AND TO_DATE IS NULL) OR FROM_DATE > TO_DATE' INTO V_ROWS;
            DBMS_OUTPUT.PUT_LINE('Invalid schedule pairs: ' || V_ROWS);
        ELSIF V_COUNT = 1 THEN
            RAISE_APPLICATION_ERROR(-20006, 'Only one schedule column exists. Inspect partial migration; do not infer missing values.');
        END IF;
    END IF;
END;
