-- Based on r3-legacy-only validator; customer checks tightened to ASCII A-Z/0-9 for the web contract.
SET SERVEROUTPUT ON
SET LINESIZE 220
SET PAGESIZE 100
SET LONG 10000
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

DECLARE
    V_COUNT NUMBER;
BEGIN
    IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'MATERIAL'
       OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'MATERIAL' THEN
        RAISE_APPLICATION_ERROR(-20040, 'Validation expects SESSION_USER and CURRENT_SCHEMA = MATERIAL.');
    END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_TABLES WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP';
    IF V_COUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20041, 'Local PULLLIST_COSTROLLUP table was not found.'); END IF;
END;
/

SELECT SYS_CONTEXT('USERENV', 'DB_NAME') AS DB_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
FROM DUAL;
SELECT COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_USED, NULLABLE, DATA_DEFAULT
FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP' ORDER BY COLUMN_ID;
SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM USER_CONSTRAINTS WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP' ORDER BY CONSTRAINT_TYPE, CONSTRAINT_NAME;
SELECT CONSTRAINT_NAME, SEARCH_CONDITION
FROM USER_CONSTRAINTS WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP' AND CONSTRAINT_TYPE = 'C';

-- These four result sets must be empty. No remediation is performed here.
SELECT CUST_CODE, COUNT(*) AS ROW_COUNT
FROM PULLLIST_COSTROLLUP GROUP BY CUST_CODE HAVING COUNT(*) > 1;
SELECT CUST_CODE, COSTROLLUP_STATUS
FROM PULLLIST_COSTROLLUP
WHERE CUST_CODE IS NULL OR COSTROLLUP_STATUS IS NULL OR COSTROLLUP_STATUS NOT IN ('Y', 'N');
SELECT CUST_CODE, COSTROLLUP_STATUS, CHANGE_BY
FROM PULLLIST_COSTROLLUP
WHERE NOT REGEXP_LIKE(CUST_CODE, '^[A-Z0-9]{2}$', 'c')
   OR (CHANGE_BY IS NOT NULL AND TRIM(CHANGE_BY) IS NULL);
SELECT CUST_CODE, FROM_DATE, TO_DATE FROM PULLLIST_COSTROLLUP
WHERE (FROM_DATE IS NULL AND TO_DATE IS NOT NULL)
   OR (FROM_DATE IS NOT NULL AND TO_DATE IS NULL) OR FROM_DATE > TO_DATE;

-- Review unknown owners. Do not assume NULL means SERVICE or an admin EN.
SELECT COSTROLLUP_STATUS, COUNT(*) AS UNKNOWN_OWNER_ROWS
FROM PULLLIST_COSTROLLUP WHERE CHANGE_BY IS NULL GROUP BY COSTROLLUP_STATUS;

DECLARE
    V_COUNT NUMBER;
    V_DEFAULT_OK NUMBER := 0;
    V_CHECK_OK NUMBER := 0;
    V_DATE_CHECK NUMBER := 0;
    V_EXPRESSION VARCHAR2(32767);
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP';
    IF V_COUNT <> 7 THEN RAISE_APPLICATION_ERROR(-20042, 'Expected seven columns; inspect schema drift.'); END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP'
      AND ((COLUMN_NAME = 'CUST_CODE' AND DATA_TYPE = 'VARCHAR2' AND DATA_LENGTH = 2 AND CHAR_USED = 'B' AND NULLABLE = 'N')
        OR (COLUMN_NAME = 'COSTROLLUP_STATUS' AND DATA_TYPE = 'VARCHAR2' AND DATA_LENGTH = 1 AND CHAR_USED = 'B' AND NULLABLE = 'N')
        OR (COLUMN_NAME = 'MISLIP_NO_REF' AND DATA_TYPE = 'VARCHAR2' AND DATA_LENGTH = 50 AND CHAR_USED = 'B' AND NULLABLE = 'Y')
        OR (COLUMN_NAME = 'LAST_UPDATE' AND DATA_TYPE = 'DATE' AND NULLABLE = 'Y')
        OR (COLUMN_NAME = 'CHANGE_BY' AND DATA_TYPE = 'VARCHAR2' AND DATA_LENGTH = 50 AND CHAR_USED = 'B' AND NULLABLE = 'Y')
        OR (COLUMN_NAME = 'FROM_DATE' AND DATA_TYPE = 'DATE' AND NULLABLE = 'Y')
        OR (COLUMN_NAME = 'TO_DATE' AND DATA_TYPE = 'DATE' AND NULLABLE = 'Y'));
    IF V_COUNT <> 7 THEN RAISE_APPLICATION_ERROR(-20043, 'Column type/size/nullability differs from the service contract.'); END IF;
    FOR C IN (SELECT DATA_DEFAULT FROM USER_TAB_COLUMNS
              WHERE TABLE_NAME = 'PULLLIST_COSTROLLUP' AND COLUMN_NAME = 'COSTROLLUP_STATUS') LOOP
        V_EXPRESSION := C.DATA_DEFAULT;
        -- Trim formatting around the literal, never spaces inside ' N' or 'N '.
        V_EXPRESSION := REGEXP_REPLACE(V_EXPRESSION, '^[[:space:]]+|[[:space:]]+$', '');
        IF V_EXPRESSION = '''N''' THEN V_DEFAULT_OK := 1; END IF;
    END LOOP;
    IF V_DEFAULT_OK <> 1 THEN RAISE_APPLICATION_ERROR(-20044, 'COSTROLLUP_STATUS must default to N.'); END IF;
    SELECT COUNT(*) INTO V_COUNT FROM USER_CONSTRAINTS C
    WHERE C.TABLE_NAME = 'PULLLIST_COSTROLLUP' AND C.CONSTRAINT_TYPE = 'P'
      AND C.STATUS = 'ENABLED' AND C.VALIDATED = 'VALIDATED'
      AND (SELECT COUNT(*) FROM USER_CONS_COLUMNS CC WHERE CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME) = 1
      AND EXISTS (SELECT 1 FROM USER_CONS_COLUMNS CC WHERE CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME AND CC.COLUMN_NAME = 'CUST_CODE');
    IF V_COUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20045, 'Expected enabled/validated CUST_CODE primary key only.'); END IF;
    -- Every enabled status CHECK can restrict writes, even an ENABLE NOVALIDATE check.
    FOR C IN (SELECT UC.CONSTRAINT_NAME, UC.SEARCH_CONDITION, UC.VALIDATED FROM USER_CONSTRAINTS UC
              WHERE UC.TABLE_NAME = 'PULLLIST_COSTROLLUP' AND UC.CONSTRAINT_TYPE = 'C'
                AND UC.STATUS = 'ENABLED'
                AND EXISTS (SELECT 1 FROM USER_CONS_COLUMNS CC
                            WHERE CC.CONSTRAINT_NAME = UC.CONSTRAINT_NAME AND CC.COLUMN_NAME = 'COSTROLLUP_STATUS')) LOOP
        V_EXPRESSION := C.SEARCH_CONDITION;
        -- Match formatting outside literals only; 'Y ', '(Y)' and 'y' are not 'Y'.
        -- Stored CHECK expressions already have valid Oracle syntax, including outer parentheses.
        IF REGEXP_LIKE(V_EXPRESSION,
            '^[[:space:]]*([(][[:space:]]*)*("COSTROLLUP_STATUS"|[Cc][Oo][Ss][Tt][Rr][Oo][Ll][Ll][Uu][Pp]_[Ss][Tt][Aa][Tt][Uu][Ss])[[:space:]]+[Ii][Nn][[:space:]]*[(][[:space:]]*(''Y''[[:space:]]*,[[:space:]]*''N''|''N''[[:space:]]*,[[:space:]]*''Y'')[[:space:]]*[)]([[:space:]]*[)])*[[:space:]]*$', 'c') THEN
            IF C.VALIDATED = 'VALIDATED' THEN V_CHECK_OK := 1; END IF;
        ELSIF NOT REGEXP_LIKE(V_EXPRESSION,
            '^[[:space:]]*([(][[:space:]]*)*("COSTROLLUP_STATUS"|[Cc][Oo][Ss][Tt][Rr][Oo][Ll][Ll][Uu][Pp]_[Ss][Tt][Aa][Tt][Uu][Ss])[[:space:]]+[Ii][Ss][[:space:]]+[Nn][Oo][Tt][[:space:]]+[Nn][Uu][Ll][Ll]([[:space:]]*[)])*[[:space:]]*$', 'c') THEN
            RAISE_APPLICATION_ERROR(-20048, 'Unrecognized enabled status check: ' || C.CONSTRAINT_NAME || '. Review with the DBA; no constraint was removed.');
        END IF;
    END LOOP;
    IF V_CHECK_OK <> 1 THEN
        RAISE_APPLICATION_ERROR(-20046, 'Expected enabled/validated IN (Y,N) check. Inspect alternative expressions with the DBA.');
    END IF;
    -- Preserve internal grouping while matching this package's date-pair expression.
    FOR C IN (SELECT UC.CONSTRAINT_NAME, UC.SEARCH_CONDITION, UC.VALIDATED FROM USER_CONSTRAINTS UC
              WHERE UC.TABLE_NAME = 'PULLLIST_COSTROLLUP' AND UC.CONSTRAINT_TYPE = 'C'
                AND UC.STATUS = 'ENABLED'
                AND EXISTS (SELECT 1 FROM USER_CONS_COLUMNS CC
                            WHERE CC.CONSTRAINT_NAME = UC.CONSTRAINT_NAME AND CC.COLUMN_NAME IN ('FROM_DATE', 'TO_DATE'))) LOOP
        V_EXPRESSION := C.SEARCH_CONDITION;
        V_EXPRESSION := UPPER(REPLACE(REGEXP_REPLACE(V_EXPRESSION, '[[:space:]]', ''), '"', ''));
        IF V_EXPRESSION IN (
            '(FROM_DATEISNULLANDTO_DATEISNULL)OR(FROM_DATEISNOTNULLANDTO_DATEISNOTNULLANDFROM_DATE<=TO_DATE)',
            '((FROM_DATEISNULLANDTO_DATEISNULL)OR(FROM_DATEISNOTNULLANDTO_DATEISNOTNULLANDFROM_DATE<=TO_DATE))',
            '(((FROM_DATEISNULLANDTO_DATEISNULL)OR(FROM_DATEISNOTNULLANDTO_DATEISNOTNULLANDFROM_DATE<=TO_DATE)))') THEN
            IF C.VALIDATED = 'VALIDATED' THEN V_DATE_CHECK := 1; END IF;
        ELSE
            RAISE_APPLICATION_ERROR(-20049, 'Unrecognized enabled schedule check: ' || C.CONSTRAINT_NAME || '. Review with DBA; no constraint was removed.');
        END IF;
    END LOOP;
    IF V_DATE_CHECK <> 1 THEN RAISE_APPLICATION_ERROR(-20050, 'Expected enabled/validated date-pair check.'); END IF;
    SELECT COUNT(*) INTO V_COUNT FROM PULLLIST_COSTROLLUP
    WHERE CUST_CODE IS NULL OR NOT REGEXP_LIKE(CUST_CODE, '^[A-Z0-9]{2}$', 'c')
       OR COSTROLLUP_STATUS IS NULL OR COSTROLLUP_STATUS NOT IN ('Y', 'N')
       OR (CHANGE_BY IS NOT NULL AND TRIM(CHANGE_BY) IS NULL)
       OR (FROM_DATE IS NULL AND TO_DATE IS NOT NULL)
       OR (FROM_DATE IS NOT NULL AND TO_DATE IS NULL) OR FROM_DATE > TO_DATE;
    IF V_COUNT <> 0 THEN RAISE_APPLICATION_ERROR(-20047, 'Invalid data remains; review result sets above.'); END IF;
    DBMS_OUTPUT.PUT_LINE('PASS: schema and stored-data checks. This does not verify web permissions, DB bindings, or service/SAP runtime.');
END;
